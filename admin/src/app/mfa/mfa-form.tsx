"use client";

import { useState, useTransition } from "react";
import { useRouter } from "next/navigation";
import { startEnroll, verifyTotp, type EnrollData } from "@/lib/actions/auth";

export function MfaForm({ verifiedFactorId }: { verifiedFactorId: string | null }) {
  const router = useRouter();
  const [enroll, setEnroll] = useState<EnrollData | null>(null);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [pending, start] = useTransition();
  const factorId = verifiedFactorId ?? enroll?.factorId ?? null;

  function begin() {
    setError(null);
    start(async () => {
      const r = await startEnroll();
      if (!r.ok || !r.data) setError(r.ok ? "Enrolment failed" : r.error);
      else setEnroll(r.data);
    });
  }

  function submit(e: React.FormEvent) {
    e.preventDefault();
    if (!factorId) return;
    setError(null);
    start(async () => {
      const r = await verifyTotp(factorId, code);
      if (!r.ok) setError(r.error === "validation" ? "Enter the 6-digit code" : r.error);
      else router.push("/dashboard");
    });
  }

  return (
    <div className="card space-y-4">
      {!verifiedFactorId && !enroll ? (
        <button className="btn w-full" onClick={begin} disabled={pending}>
          {pending ? "Preparing..." : "Set up authenticator"}
        </button>
      ) : null}
      {enroll ? (
        <div className="space-y-2 text-sm">
          {/* QR is an SVG data URI generated by Supabase Auth */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={enroll.qrSvg} alt="TOTP QR code" className="mx-auto h-44 w-44 rounded bg-white p-2" />
          <p className="text-muted">
            Or enter this key manually: <code className="break-all text-white">{enroll.secret}</code>
          </p>
        </div>
      ) : null}
      {factorId ? (
        <form onSubmit={submit} className="space-y-3">
          <label className="label" htmlFor="code">
            6-digit code
          </label>
          <input
            id="code"
            inputMode="numeric"
            autoComplete="one-time-code"
            pattern="\d{6}"
            maxLength={6}
            value={code}
            onChange={(e) => setCode(e.target.value.replace(/\D/g, ""))}
            className="input tracking-widest"
            required
          />
          <button className="btn w-full" disabled={pending || code.length !== 6}>
            {pending ? "Verifying..." : "Verify"}
          </button>
        </form>
      ) : null}
      {error ? (
        <p role="alert" className="text-sm text-danger">
          {error}
        </p>
      ) : null}
    </div>
  );
}
